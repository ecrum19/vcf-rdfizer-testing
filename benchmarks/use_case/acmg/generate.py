#!/usr/bin/env python3
"""Write policy.ttl and carriers.rq, the RDF route's inputs, from use_case.json.

The RDF route and the bcftools baseline read the same definitions, and neither
reads the other. That is what makes their agreement a test: the baseline
applies the consent table in Python, the RDF route applies these rules through
vcf-rdfizer-policy, and the experiment requires identical carrier lists.

Two kinds of policy:

* one consent per participant, attached to that participant's file;
* one cohort rule, "cancer-predisposition genes are released only for clinical
  care", whose target is the shipped LinkedSelector over the 28 genes' Ensembl
  IRIs (from regions.json): a gene panel stated as data.

carriers.rq is the one SPARQL query that answers the question. It joins each
genome's calls to ClinVar's through the shared SPDI identifier the spdi linker
writes (vcfl:sameVariantAs), so no join relies on the files' own IRIs or on
their contig names agreeing.

Usage:
    python3 generate.py [out-dir [case.json]]   # default: beside this script, use_case.json
    python3 generate.py cohort cohort/cohort.json  # arm 2
"""

from __future__ import annotations

import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
EX = "https://example.org/policy/acmg-use-case/"

PREAMBLE = f"""\
# GENERATED by generate.py from use_case.json and regions.json; do not edit.
#
# The consents are SIMULATED. The genomes are real public genomes and nobody
# consented to anything here; the policies exist to show what governed release
# of real data looks like, and are checked against an independent baseline.

@prefix odrl: <http://www.w3.org/ns/odrl/2/> .
@prefix vcfp: <https://w3id.org/vcf-rdfizer/policy#> .
@prefix obo:  <http://purl.obolibrary.org/obo/> .
@prefix vcfl: <https://w3id.org/vcf-rdfizer/linking#> .
@prefix ensembl: <https://identifiers.org/ensembl:> .
@prefix ex:   <{EX}> .
"""


def duo(curie: str) -> str:
    return "obo:DUO_" + curie.split(":")[1]


def gene_panel(genes: list[str], regions: dict[str, dict]) -> str:
    entities = "\n".join(f"        ensembl:{regions[g]['ensembl_id']}  # {g}" for g in genes)
    return f"""
# The cohort rule's target: records whose call overlaps one of these Ensembl
# genes (vcfl:overlapsGene, written by the ensembl-genes-grch38 linker), through
# the LinkedSelector the VCF Core profile ships. The panel is data, not SPARQL,
# and the selector refuses a graph evaluated without its gene links.
ex:cancer-predisposition a odrl:Asset , vcfp:GraphSelection ;
    vcfp:selector [ a vcfp:LinkedSelector ; vcfp:predicate vcfl:overlapsGene ;
                    vcfp:entities (
{entities}
    ) ] .
"""


def cohort_rule(clinical: str) -> str:
    return f"""
ex:cohort a odrl:Set ; odrl:uid ex:cohort ;
    odrl:profile <https://w3id.org/vcf-rdfizer/policy> ; odrl:conflict odrl:prohibit ;
    # Secondary findings in cancer-predisposition genes: clinical care only.
    odrl:prohibition [ odrl:target ex:cancer-predisposition ; odrl:action odrl:read ; odrl:assignee odrl:All ;
        odrl:constraint [ odrl:leftOperand odrl:purpose ; odrl:operator odrl:isNoneOf ;
                          odrl:rightOperand {duo(clinical)} ] ] .
"""


def consent(participant: str, terms: dict) -> str:
    target = f"<file://{participant}.acmg.vcf>"
    purposes = " , ".join(duo(p) for p in terms["permits"])
    text = f"""
ex:consent-{participant} a odrl:Set ; odrl:uid ex:consent-{participant} ;
    odrl:profile <https://w3id.org/vcf-rdfizer/policy> ; odrl:conflict odrl:prohibit ;
    odrl:permission [ odrl:target {target} ; odrl:action odrl:read ; odrl:assignee odrl:All ;
        odrl:constraint [ odrl:leftOperand odrl:purpose ; odrl:operator odrl:isAnyOf ;
                          odrl:rightOperand {purposes} ] ] """
    if terms.get("withdrawn"):
        # A withdrawal is a prohibition, so it overrides the permission (deny wins).
        text += f""";
    odrl:prohibition [ odrl:target {target} ; odrl:action odrl:read ; odrl:assignee odrl:All ] """
    return text + ".\n"


SPDI_BASE = "https://api.ncbi.nlm.nih.gov/variation/v0/spdi/"  # the spdi linker's object namespace
CLINVAR_FILE = "file://clinvar.acmg.vcf"                         # derive.sh names it
PANEL_FILE = "file://panel.acmg.vcf"                             # the cohort's frequencies, likewise


def panel_subquery(panel: dict) -> str:
    rare = panel["rare"]
    return f"""
  # The panel's frequency for each variant, recorded once in its own sites-only
  # file rather than in every participant's.
  {{ SELECT ?variant ?af WHERE {{
      <{PANEL_FILE}> vcfc:hasRecord ?panelRecord .
      ?panelRecord vcfc:hasCall ?panelCall .
      ?panelCall vcfl:sameVariantAs ?variant ; vcfc:hasInfoValue ?frequency .
      ?frequency vcfc:declaredBy ?frequencyDef ; vcfc:fieldValueDecimal ?af .
      ?frequencyDef vcfc:fieldId "{rare['field']}" .
      FILTER(?af < {rare['below']}) }} }}
"""


def carriers_query(case: dict, genes: list[str], panel: dict | None = None) -> str:
    """carriers.rq; with `panel`, rare.rq: the same carriers, restricted to rare variants."""
    d = case["definition"]
    excluded = ", ".join(f'"{s}"' for s in d["excluded_review_status"])
    gene_values = " ".join(f'"{g}"' for g in genes)
    rare = "" if panel is None else (
        f"# Only variants with the panel's {panel['rare']['field']} below {panel['rare']['below']}.\n")
    return f"""# GENERATED by generate.py from use_case.json; do not edit.
#
# Carriers of a ClinVar-classified variant in an ACMG SF v3.2 gene, with the
# classification returned rather than filtered on. Run it over a requester's
# release view plus the ClinVar graph and the link graphs; what the view
# withholds cannot match.
{rare}#
# Two tables joined on the SPDI identifier both sides link to, never on the
# files' own IRIs or contig names. Each table is a subquery so an engine plans
# it on its own: as one group of ~20 patterns, QLever's planner either takes
# exponential time or picks a cross product (workstream-a-implementation.md,
# progress log, 2026-09-28).

PREFIX vcfc: <https://w3id.org/vcf-core/vocab#>
PREFIX vcfl: <https://w3id.org/vcf-rdfizer/linking#>

SELECT DISTINCT ?file ?sample ?gene ?chrom ?pos ?ref ?alt ?variant ?clnsig ?gt{"" if panel is None else " ?af"}
WHERE {{
  # Genome calls that carry the ALT, FILTER PASS or missing.
  {{ SELECT ?file ?sample ?chrom ?pos ?ref ?alt ?variant ?gt WHERE {{
      ?file vcfc:hasRecord ?record .
      ?record vcfc:chrom ?chrom ; vcfc:pos ?pos ; vcfc:ref ?ref ; vcfc:alt ?alt ;
              vcfc:hasCall ?call .
      ?call vcfc:filterStatus ?status ; vcfc:hasSampleCall ?sampleCall ;
            vcfl:sameVariantAs ?variant .
      ?sampleCall vcfc:sampleId ?sample ; vcfc:hasGenotype ?genotype .
      ?genotype vcfc:genotypeString ?gt .
      FILTER(?status IN (vcfc:FiltersPassed, vcfc:FiltersNotApplied))
      FILTER(STRSTARTS(STR(?variant), "{SPDI_BASE}"))
      FILTER(REGEX(STR(?gt), "[1-9]"))
      FILTER(?file != <{CLINVAR_FILE}>) }} }}

  # ClinVar's classification and gene annotation for each variant, one star or more.
  {{ SELECT ?variant ?clnsig ?geneinfo WHERE {{
      <{CLINVAR_FILE}> vcfc:hasRecord ?cvRecord .
      ?cvRecord vcfc:hasCall ?clinvar .
      ?clinvar vcfl:sameVariantAs ?variant ;
               vcfc:hasInfoValue ?sig , ?rev , ?info .
      ?sig vcfc:declaredBy ?sigDef ; vcfc:fieldValue ?clnsig .
      ?sigDef vcfc:fieldId "CLNSIG" .
      ?rev vcfc:declaredBy ?revDef ; vcfc:fieldValue ?revstat .
      ?revDef vcfc:fieldId "CLNREVSTAT" .
      ?info vcfc:declaredBy ?infoDef ; vcfc:fieldValue ?geneinfo .
      ?infoDef vcfc:fieldId "GENEINFO" .
      FILTER(STR(?revstat) NOT IN ({excluded})) }} }}
{"" if panel is None else panel_subquery(panel)}
  # The ACMG genes ClinVar names, matched after the join so the gene list meets
  # only the joined rows, not every ClinVar record.
  VALUES ?gene {{ {gene_values} }}
  FILTER(REGEX(STR(?geneinfo), CONCAT("(^|\\\\|)", ?gene, ":")))
}}
ORDER BY ?file ?gene ?pos ?alt
"""


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    out = pathlib.Path(argv[0]) if argv else HERE
    case_path = pathlib.Path(argv[1]) if len(argv) > 1 else HERE / "use_case.json"
    out.mkdir(parents=True, exist_ok=True)
    case = json.loads(case_path.read_text(encoding="utf-8"))
    regions = {r["symbol"]: r for r in json.loads((HERE / "regions.json").read_text(encoding="utf-8"))["regions"]}
    policy = case["policy"]
    genes = policy["secondary_findings"]["genes"]
    missing = [g for g in genes if g not in regions]
    if missing:
        raise SystemExit(f"secondary-findings genes not in regions.json: {missing}")

    parts = [PREAMBLE, "\n# --- Cohort rule -------------------------------------------------------------\n",
             gene_panel(genes, regions), cohort_rule("DUO:0000043"),
             "\n# --- Participant consents (simulated) -----------------------------------------\n"]
    parts += [consent(pid, terms) for pid, terms in policy["consents"].items()]
    (out / "policy.ttl").write_text("".join(parts), encoding="utf-8")
    acmg = [g.strip() for g in (HERE / "acmg_sf_v3.2.genes.txt").read_text(encoding="utf-8").splitlines()
            if g.strip() and not g.startswith("#")]
    (out / "carriers.rq").write_text(carriers_query(case, acmg), encoding="utf-8")
    if "panel" in case:
        (out / "rare.rq").write_text(carriers_query(case, acmg, case["panel"]), encoding="utf-8")
    print(f"policy.ttl: {len(policy['consents'])} consents, {len(genes)} restricted genes; "
          f"carriers.rq: {len(acmg)} genes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
